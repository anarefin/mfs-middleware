#!/usr/bin/env node
// Generates the Bits MFS middleware Postman collection (ticket 58) from its sources:
//
//   node tests/api/build_collection.mjs           writes mfs-mw.postman_collection.json
//   node tests/api/build_collection.mjs --check   fails (exit 1) when the committed file is stale
//
// Sources: src/<NN-folder>/folder.json ({name, description}) and src/<NN-folder>/*.js, each an ES
// module whose default export is a list of scenarios {name, run}. `name` starts with the
// requirement tags in brackets; optional `args` (JSON) is the third argument of `run` (outline rows) ("[p2p tsq] ..."; scripts/check-api-traceability.sh checks them
// against TRACEABILITY.md); `run` is an `async (MW, S) => { ... }` function that drives the
// scenario through lib.js (MW: the APIs, S: the scenario's state and checks). Its source text
// becomes the item's test script, so it may use only MW, S and plain JavaScript (no imports, no
// module-level variables); functions a file exports as `helpers` are copied into each of its
// scripts (shared steps of one folder). The item's own request is the edge health check (GET /healthz); the
// scenario's calls are pm.sendRequest calls made by the script.
// lib.js is embedded as the collection variable "lib"; fixtures/*.json as the variable "fixtures".
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'mfs-mw.postman_collection.json');
const ENV = join(HERE, 'local.postman_environment.json');

// Pinned third-party code for the Postman sandbox (no RSA-OAEP or ECDSA there): lib.js evaluates
// only a file whose SHA-256 is this one.
const PINNED = {
  forgeUrl: 'https://cdnjs.cloudflare.com/ajax/libs/forge/1.3.1/forge.min.js',
  forgeSha256: 'dc67fd132427ad96c9666c844b39565413c40ddb1f2d063c53512fbf6d387dfd',
  ellipticUrl: 'https://cdnjs.cloudflare.com/ajax/libs/elliptic/6.6.1/elliptic.min.js',
  ellipticSha256: 'e8ddf337e838c19af137969f620dd7ddcfdf238de797293034169d8a9a63fcae',
};
const PRELUDE = "const MW = eval(pm.collectionVariables.get('lib'));";

async function folders() {
  const src = join(HERE, 'src');
  const out = [];
  for (const dir of readdirSync(src).filter(d => /^\d\d-/.test(d)).sort()) {
    const meta = JSON.parse(readFileSync(join(src, dir, 'folder.json'), 'utf8'));
    const items = [];
    for (const f of readdirSync(join(src, dir)).filter(f => f.endsWith('.js')).sort()) {
      const mod = await import(pathToFileURL(join(src, dir, f)).href);
      for (const s of mod.default) {
        if (typeof s.name !== 'string' || typeof s.run !== 'function') throw new Error(`${dir}/${f}: a scenario needs name and run`);
        items.push(item(s, (mod.helpers || []).map(h => h.toString())));
      }
    }
    const names = items.map(i => i.name);
    const dup = names.find((n, i) => names.indexOf(n) !== i);
    if (dup) throw new Error(`${dir}: request name used twice: ${dup}`);
    out.push({ name: meta.name, description: meta.description || '', item: items });
  }
  return out;
}

function item(s, helpers) {
  const script = [PRELUDE, ...helpers, `MW.run(${JSON.stringify(s.name)}, ${s.run.toString()}, ${JSON.stringify(s.args === undefined ? null : s.args)});`].join('\n');
  return {
    name: s.name,
    event: [{ listen: 'test', script: { type: 'text/javascript', exec: script.split('\n') } }],
    request: { method: 'GET', header: [], url: '{{baseUrl}}/healthz', description: s.description || '' },
  };
}

function fixtures() {
  const dir = join(HERE, 'fixtures');
  const out = {};
  if (existsSync(dir)) {
    for (const f of readdirSync(dir).filter(f => f.endsWith('.json')).sort()) out[f.replace(/\.json$/, '')] = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  }
  return out;
}

async function collection() {
  const variable = [
    { key: 'lib', value: readFileSync(join(HERE, 'lib.js'), 'utf8') },
    { key: 'fixtures', value: JSON.stringify(fixtures()) },
    ...Object.entries(PINNED).map(([key, value]) => ({ key, value })),
  ];
  return {
    info: {
      name: 'Bits MFS middleware API suite',
      description: 'Generated by tests/api/build_collection.mjs from tests/api/src and lib.js; do not edit by hand.',
      schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
    },
    item: await folders(),
    variable,
  };
}

function environment() {
  const values = [
    ['baseUrl', 'https://localhost:443'], ['ocsTimeoutMs', '20000'],
    ['e2eApiKey', ''], ['kcCustomersPassword', ''], ['kcPortalsPassword', ''], ['kcOpsPassword', ''],
    ['kcOpsTotpSecret', ''], ['billaggSecret', ''], ['checkoutSecret', ''],
  ].map(([key, value]) => ({ key, value, enabled: true }));
  return { name: 'Bits MFS middleware local stack', values, _postman_variable_scope: 'environment' };
}

const text = JSON.stringify(await collection(), null, 2) + '\n';
const envText = JSON.stringify(environment(), null, 2) + '\n';
if (process.argv.includes('--check')) {
  const stale = [[OUT, text], [ENV, envText]].filter(([p, t]) => !existsSync(p) || readFileSync(p, 'utf8') !== t).map(([p]) => p);
  if (stale.length) {
    console.error('stale (run node tests/api/build_collection.mjs): ' + stale.join(', '));
    process.exit(1);
  }
  console.log('collection up to date');
} else {
  writeFileSync(OUT, text);
  writeFileSync(ENV, envText);
  console.log('wrote ' + OUT);
}
