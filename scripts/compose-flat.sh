#!/usr/bin/env bash
# Generates the repo-root compose.yml: the whole MVP stack (deploy/compose/mvp/compose.yml with its
# includes, merged with the low-resource override compose.lowmem.yml) as one flat file.
# Usage: scripts/compose-flat.sh           write compose.yml
#        scripts/compose-flat.sh --check   fail when compose.yml is out of date (make verify)
# Both modes check the memory budget: the limits of all long-running services (no
# mw.oneshot=true label) add up to <= MW_RAM_BUDGET_MIB (default 10240), and each has a limit.
#
# `config --no-interpolate` keeps every ${VAR} as a placeholder, so no generated dev secret
# reaches the file; absolute paths are rewritten to repo-relative ones. Run the result with:
#   docker compose --env-file deploy/compose/platform/.env up -d --build
# (jars first: `make up` or ./gradlew bootJar per module; the images copy build/libs/*.jar).
# Needs the docker compose CLI and node (>= 22, as contracts-lint).
set -eu
. "$(dirname "$0")/lib/modules.sh"

mode="${1:-write}"
case "$mode" in write|--check) ;; *) die "usage: compose-flat.sh [--check]" ;; esac

src="$MW_ROOT/deploy/compose/mvp/compose.yml"
over="$MW_ROOT/deploy/compose/mvp/compose.lowmem.yml"
out="$MW_ROOT/compose.yml"
budget="${MW_RAM_BUDGET_MIB:-10240}"

[ -f "$src" ] || { info "compose-flat: no deploy/compose/mvp/compose.yml, nothing to flatten"; exit 0; }
docker compose version >/dev/null 2>&1 || die "compose-flat: the docker compose CLI is required"
command -v node >/dev/null 2>&1 || die "compose-flat: node (>= 22) is required"

args=(-f "$src")
[ -f "$over" ] && args+=(-f "$over")

tmp="$(mktemp -d "${TMPDIR:-/tmp}/compose-flat.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT

# Variables still referenced as ${VAR}; compose must not need their values for --no-interpolate,
# but a missing required one would fail the parse, so none are passed.
docker compose "${args[@]}" config --no-interpolate >"$tmp/body.yml" 2>"$tmp/err" \
  || { cat "$tmp/err" >&2; die "compose-flat: docker compose config failed"; }
docker compose "${args[@]}" config --no-interpolate --format json >"$tmp/model.json" 2>/dev/null \
  || die "compose-flat: docker compose config --format json failed"

# Budget: sum of long-running memory limits, every long-running service limited.
node - "$tmp/model.json" "$budget" <<'EOF' || exit 1
const fs = require('node:fs');
const [file, budget] = process.argv.slice(2);
const model = JSON.parse(fs.readFileSync(file, 'utf8'));
const kv = (x) => Array.isArray(x)
  ? Object.fromEntries(x.map((i) => { const k = i.indexOf('='); return k < 0 ? [i, ''] : [i.slice(0, k), i.slice(k + 1)]; }))
  : (x || {});
const mib = (v) => {
  if (typeof v === 'number') return v / 1048576;
  const m = /^\s*([0-9.]+)\s*([kmg]?)b?\s*$/i.exec(String(v));
  if (!m) return NaN;
  return Number(m[1]) * { '': 1 / 1048576, k: 1 / 1024, m: 1, g: 1024 }[m[2].toLowerCase()];
};
let total = 0; const missing = []; const rows = [];
for (const [name, svc] of Object.entries(model.services || {}).sort()) {
  if (kv(svc.labels)['mw.oneshot'] === 'true') continue;
  const lim = svc.deploy?.resources?.limits?.memory;
  const m = lim === undefined ? NaN : mib(lim);
  if (Number.isNaN(m)) { missing.push(name); continue; }
  total += m; rows.push(`${name}=${Math.round(m)}`);
}
if (missing.length) {
  console.error(`error: compose-flat: long-running service(s) without a memory limit: ${missing.join(' ')}`);
  process.exit(1);
}
if (total > Number(budget)) {
  console.error(`error: compose-flat: memory limits of long-running services add up to ${Math.round(total)} MiB, over the ${budget} MiB budget (${rows.join(' ')})`);
  process.exit(1);
}
console.log(`==> compose-flat: long-running memory limits ${Math.round(total)} MiB of ${budget} MiB`);
EOF

# Repo-relative paths (bind mounts, env_file, build contexts).
sed -e "s#$MW_ROOT/#./#g" -e "s#$MW_ROOT\$#.#g" -e "s#$MW_ROOT\"#.\"#g" "$tmp/body.yml" >"$tmp/rel.yml"
if grep -n -F "$MW_ROOT" "$tmp/rel.yml" >&2; then die "compose-flat: absolute repo paths left in the output"; fi

# No generated dev secret may appear literally (placeholders only).
envf="$MW_ROOT/deploy/compose/platform/.env"
if [ -f "$envf" ]; then
  while IFS='=' read -r k v; do
    case "$k" in ''|\#*) continue ;; esac
    v="${v%\"}"; v="${v#\"}"
    [ "${#v}" -ge 8 ] || continue
    grep -q -F -- "$v" "$tmp/rel.yml" && die "compose-flat: the value of $k from $(basename "$envf") appears in the output"
  done <"$envf"
fi

{
  cat <<'EOF'
# GENERATED by scripts/compose-flat.sh from deploy/compose/mvp/compose.yml (its includes) and
# deploy/compose/mvp/compose.lowmem.yml. Do not edit: change those files, then `make compose-flat`.
# `make verify` fails when this file is out of date.
#
# The whole MVP stack in one file, low-resource limits (functional runs only, no load tests).
# Run from the repo root:
#   scripts/gen-dev-env.sh                         # once: dev credentials (gitignored .env)
#   make up   (or ./gradlew bootJar in each services/mw-*)   # the images copy build/libs/*.jar
#   docker compose --env-file deploy/compose/platform/.env up -d --build
#   docker compose --env-file deploy/compose/platform/.env down        # add -v to drop volumes
EOF
  cat "$tmp/rel.yml"
} >"$tmp/compose.yml"

if [ "$mode" = --check ]; then
  if [ ! -f "$out" ] || ! diff -q "$tmp/compose.yml" "$out" >/dev/null; then
    diff -u "$out" "$tmp/compose.yml" 2>/dev/null | head -40 >&2 || true
    die "compose-flat: compose.yml is out of date (run make compose-flat)"
  fi
  info "compose-flat: compose.yml is up to date"
else
  cp "$tmp/compose.yml" "$out"
  info "compose-flat: wrote compose.yml ($(wc -l <"$out" | tr -d ' ') lines)"
fi
