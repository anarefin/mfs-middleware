# make compose-flat / compose-check: the generated root compose.yml (whole MVP stack, one flat
# file, low-resource override merged in) and its memory budget guard. Uses the real
# `docker compose config` (no daemon needed); skipped when the compose CLI is missing.

have_compose() {
  docker compose version >/dev/null 2>&1 && command -v node >/dev/null 2>&1 && return 0
  echo "    SKIP: docker compose CLI or node missing" >&2; return 1
}

# mini_stack ROOT: platform (one long-running service with a bind mount and a secret, one
# one-shot) + one module, included by an mvp file, and a low-resource override.
mini_stack() {
  local r="$1"
  mkdir -p "$r/deploy/compose/mvp" "$r/deploy/compose/platform/conf" "$r/services/mw-a"
  cat >"$r/deploy/compose/platform/compose.yml" <<'EOF'
services:
  db:
    image: postgres:18
    environment:
      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD:?run scripts/gen-dev-env.sh}
    volumes:
      - ./conf:/etc/conf:ro
    deploy:
      resources: { limits: { memory: 2g } }
  db-init:
    image: alpine:3
    labels: { mw.oneshot: "true" }
    restart: "no"
EOF
  cat >"$r/services/mw-a/compose.yml" <<'EOF'
services:
  mw-a:
    image: mw-a:dev
    build: .
    deploy:
      resources: { limits: { memory: 768M } }
EOF
  cat >"$r/deploy/compose/mvp/compose.yml" <<'EOF'
name: mw
include:
  - path: ../platform/compose.yml
  - path: ../../../services/mw-a/compose.yml
EOF
  cat >"$r/deploy/compose/mvp/compose.lowmem.yml" <<'EOF'
services:
  db:
    deploy:
      resources: { limits: { memory: 384M } }
  mw-a:
    environment: { JAVA_TOOL_OPTIONS: -Xmx160m }
    deploy:
      resources: { limits: { memory: 384M } }
EOF
  printf 'POSTGRES_PASSWORD=fake-dev-secret-0123456789\n' >"$r/deploy/compose/platform/.env"
}

flat() { OUT="$(MW_ROOT="$PWD" "$REPO_DIR/scripts/compose-flat.sh" "$@" 2>&1)"; }

test_compose_flat_writes_one_flat_portable_file_with_the_override_merged() {
  have_compose || return 0
  mini_stack "$PWD"
  flat || fail "compose-flat failed"
  [ -f compose.yml ] || fail "compose.yml not written"
  grep -q 'GENERATED by scripts/compose-flat.sh' compose.yml || fail "no generated header"
  grep -q -F "$PWD" compose.yml && fail "absolute repo path left in compose.yml"
  grep -q 'include:' compose.yml && fail "still uses include"
  grep -q 'source: ./deploy/compose/platform/conf' compose.yml || fail "bind mount not repo-relative: $(grep -n source compose.yml)"
  grep -q 'JAVA_TOOL_OPTIONS: -Xmx160m' compose.yml || fail "override not merged"
  grep -q 'memory: 2g' compose.yml && fail "base limit not overridden"
  assert_out_contains "768 MiB of 10240 MiB"
}

test_compose_flat_keeps_secrets_as_placeholders() {
  have_compose || return 0
  mini_stack "$PWD"
  flat || fail "compose-flat failed"
  grep -q -F 'fake-dev-secret-0123456789' compose.yml && fail "secret value written into compose.yml"
  grep -q -F '${POSTGRES_PASSWORD:?' compose.yml || fail "placeholder lost"
  # the flat file runs with the generated env file from the repo root
  docker compose --project-directory "$PWD" -f compose.yml --env-file deploy/compose/platform/.env config -q \
    || fail "flat file does not parse with --env-file"
}

test_compose_flat_fails_when_a_secret_value_would_be_written() {
  have_compose || return 0
  mini_stack "$PWD"
  cat >services/mw-a/compose.yml <<'EOF'
services:
  mw-a:
    image: mw-a:dev
    environment: { LEAK: fake-dev-secret-0123456789 }
    deploy:
      resources: { limits: { memory: 384M } }
EOF
  if flat; then fail "secret in output accepted"; fi
  assert_out_contains "POSTGRES_PASSWORD"
}

test_compose_check_passes_when_up_to_date_and_fails_after_a_source_change() {
  have_compose || return 0
  mini_stack "$PWD"
  flat || fail "compose-flat failed"
  flat --check || fail "check failed right after generating"
  sed -i.bak 's/memory: 384M/memory: 320M/' deploy/compose/mvp/compose.lowmem.yml
  if flat --check; then fail "stale compose.yml accepted"; fi
  assert_out_contains "make compose-flat"
}

test_compose_flat_fails_over_the_memory_budget() {
  have_compose || return 0
  mini_stack "$PWD"
  if MW_RAM_BUDGET_MIB=700 flat; then fail "768 MiB accepted under a 700 MiB budget"; fi
  assert_out_contains "over the 700 MiB budget"
  [ -f compose.yml ] && fail "compose.yml written despite the budget failure"
  return 0
}

test_compose_flat_fails_when_a_long_running_service_has_no_memory_limit() {
  have_compose || return 0
  mini_stack "$PWD"
  printf 'services:\n  mw-a:\n    image: mw-a:dev\n' >services/mw-a/compose.yml
  sed -i.bak '/^  mw-a:/,$d' deploy/compose/mvp/compose.lowmem.yml
  if flat; then fail "unlimited service accepted"; fi
  assert_out_contains "without a memory limit: mw-a"
}

test_make_compose_targets_dispatch_to_the_script() {
  have_compose || return 0
  mini_stack "$PWD"
  mw_make "$PWD" compose-flat || fail "make compose-flat failed"
  [ -f compose.yml ] || fail "make compose-flat wrote nothing"
  mw_make "$PWD" compose-check || fail "make compose-check failed"
}
