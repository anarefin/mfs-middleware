test_dev_stack_picks_the_gc_at_build_time_and_adds_only_sizes_at_run_time() {
  # The image's JVM_OPTS build arg is JAVA_TOOL_OPTIONS of every start; the dev stack picks its GC
  # through that build arg (x-jvm-build-args) and adds only sizes (JDK_JAVA_OPTIONS) at run time.
  # No AOT training at image build any more (no MW_AOT build arg).
  local j s bad=""
  j="$(compose_json)"
  for s in $(printf '%s' "$j" | jq -r '.services | to_entries[] | select(.key | test("^mw-") and (test("-init$") | not)) | select(.value.build.context != null) | select(.key != "mw-admin-ui") | .key'); do
    printf '%s' "$j" | jq -e --arg s "$s" '.services[$s] | (.environment.JAVA_TOOL_OPTIONS == null)
      and (.build.args.JVM_OPTS | test("-XX:\\+UseSerialGC"))
      and (.build.args.MW_AOT == null)
      and ((.environment.JDK_JAVA_OPTIONS // "") | test("Use[A-Za-z]+GC|CompressedOops") | not)' >/dev/null || bad="$bad $s"
  done
  [ -z "$bad" ] || fail "dev stack sets GC flags at run time, builds without Serial GC or still passes MW_AOT:$bad"
