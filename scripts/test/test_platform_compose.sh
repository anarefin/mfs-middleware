  local f="$REALMS_DIR/ops-realm.json"
  jq -e '.bruteForceProtected == true and .failureFactor <= 5 and .failureFactor >= 1
    and .waitIncrementSeconds >= 60 and .maxFailureWaitSeconds >= 900
    and .quickLoginCheckMilliSeconds >= 1000 and .minimumQuickLoginWaitSeconds >= 60' "$f" >/dev/null \
    || fail "ops realm brute-force detection is off or lax: $(jq -c '{bruteForceProtected, failureFactor, waitIncrementSeconds, maxFailureWaitSeconds, quickLoginCheckMilliSeconds, minimumQuickLoginWaitSeconds}' "$f")"
}

# Security review (sec-ops): the console's client takes the browser login only (Authorization
# Code + PKCE S256, no direct grant); the e2e operators' password grant has its own dev-only
# public client, no browser flow and no redirect URIs.
test_ops_realm_console_client_has_no_direct_grant_and_e2e_has_its_own_client() {
  local f="$REALMS_DIR/ops-realm.json"
  jq -e '.clients[] | select(.clientId == "mw-admin-ui") | .publicClient and .standardFlowEnabled
    and .directAccessGrantsEnabled == false and (.implicitFlowEnabled // false) == false
    and .attributes["pkce.code.challenge.method"] == "S256"' "$f" >/dev/null \
    || fail "mw-admin-ui: $(jq -c '.clients[] | select(.clientId == "mw-admin-ui")' "$f")"
  jq -e '.clients[] | select(.clientId == "mw-e2e-ops") | .publicClient and .directAccessGrantsEnabled
    and .standardFlowEnabled == false and (.implicitFlowEnabled // false) == false
    and ((.redirectUris // []) | length == 0) and (.serviceAccountsEnabled // false) == false' "$f" >/dev/null \
    || fail "no dev-only direct-grant client mw-e2e-ops: $(jq -c '[.clients[].clientId]' "$f")"
  jq -e '[.clients[] | select(.directAccessGrantsEnabled) | .clientId] == ["mw-e2e-ops"]' "$f" >/dev/null \
    || fail "direct grant on: $(jq -c '[.clients[] | select(.directAccessGrantsEnabled) | .clientId]' "$f")"
  grep -q "client: 'mw-e2e-ops'" "$REPO_DIR/tests/api/lib.js" \
    || fail "tests/api lib.js does not log operators in with mw-e2e-ops"
}

# ---- Keycloak production mode on PostgreSQL (ticket 49) ----

test_keycloak_runs_in_production_mode_on_its_own_postgres_database() {
  local j k
  j="$(compose_json)"
  k="$(printf '%s' "$j" | jq -c '.services.keycloak')"
  # production mode, pre-built (ticket 55): deploy/keycloak/Dockerfile runs `kc.sh build`, its
  # entrypoint is `start --optimized --import-realm`, so compose sets no command
  printf '%s' "$k" | jq -e '.command == null' >/dev/null \
    || fail "keycloak command overrides the image entrypoint: $(printf '%s' "$k" | jq -c .command)"
  grep -qE '^ENTRYPOINT .*"start", *"--optimized", *"--import-realm"' "$REPO_DIR/deploy/keycloak/Dockerfile" \
    || fail "deploy/keycloak/Dockerfile does not start --optimized --import-realm"
  printf '%s' "$k" | jq -e '.environment.KC_DB == "postgres"
    and (.environment.KC_DB_URL | test("^jdbc:postgresql://postgres:5432/keycloak$"))
    and .environment.KC_DB_USERNAME == "keycloak"
    and .environment.KC_DB_PASSWORD == "t"' >/dev/null || fail "keycloak DB settings: $(printf '%s' "$k" | jq -c .environment)"
  printf '%s' "$k" | jq -e '.networks | has("data") and has("ops")' >/dev/null || fail "keycloak must join ops and data"
  printf '%s' "$k" | jq -e '.depends_on.postgres.condition == "service_healthy"' >/dev/null || fail "keycloak must wait for postgres"
  # behind APISIX: plain HTTP inside the ops network, X-Forwarded-* trusted, hostname from
  # the request (no fixed public hostname yet), health on the management port
  printf '%s' "$k" | jq -e '.environment.KC_HTTP_ENABLED == "true"
    and .environment.KC_PROXY_HEADERS == "xforwarded"
    and .environment.KC_HOSTNAME_STRICT == "false"
    and .environment.KC_HEALTH_ENABLED == "true"' >/dev/null || fail "keycloak proxy/hostname/health settings: $(printf '%s' "$k" | jq -c .environment)"
  printf '%s' "$j" | jq -e '.services.postgres.environment.KC_DB_PASSWORD == "t"' >/dev/null || fail "postgres init lacks KC_DB_PASSWORD"
  printf '%s' "$j" | jq -e '[.services.postgres.volumes[] | select(.target == "/docker-entrypoint-initdb.d" and .read_only)] | length == 1' >/dev/null \
    || fail "postgres has no read-only init script mount"
}

