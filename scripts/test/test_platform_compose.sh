# placeholder_env: VAR=t for every generated secret, a test range for every address list (for `env`).
placeholder_env() {
  local v
  for v in $SECRET_VARS; do printf '%s=t\n' "$v"; done
  for v in $ADDRESS_VARS; do printf '%s=10.9.0.0/16\n' "$v"; done
}

# copy_deploy: a copy of deploy/ in the fixture root without the generated (gitignored)
# secrets file, so the tests never depend on or read a developer's local secrets.
copy_deploy() {
  [ -d deploy ] && return 0
  cp -R "$REPO_DIR/deploy" deploy
  rm -f deploy/.env
}

# compose_json [VAR=value...]: the resolved stack, profile core (every service), as JSON (default
# env, so MW_HTTPS_PORT=443), with placeholder values for the generated secrets.
# COMPOSE_PROFILE / COMPOSE_ENV_FILES pick another profile or extra --env-file (e.g. test timers).
compose_json() {
  copy_deploy
  local ef=() pf=() f p
  for f in ${COMPOSE_ENV_FILES:-}; do ef+=(--env-file "$f"); done
  # COMPOSE_PROFILE: one or more profiles, space-separated (default core)
  for p in ${COMPOSE_PROFILE:-core}; do pf+=(--profile "$p"); done
  env -u MW_HTTPS_PORT -u MW_OPS_SUBNET -u COMPOSE_PROJECT_NAME $(placeholder_env) "$@" \
    docker compose -f deploy/docker-compose.yml ${ef[@]+"${ef[@]}"} "${pf[@]}" config --format json 2>/dev/null
}

test_one_hand_written_stack_file_with_every_platform_service() {
  [ -f "$STACK_FILE" ] || fail "missing deploy/docker-compose.yml"
  grep -q '^include:' "$STACK_FILE" && fail "deploy/docker-compose.yml still includes other files"
  local services j
  j="$(COMPOSE_PROFILE="core seed tester" compose_json)" || fail "compose config failed"
  [ "$(printf '%s' "$j" | jq -r .name)" = mfs-mw ] || fail "project name is not mfs-mw"
  services="$(printf '%s' "$j" | jq -r '.services | keys[]')"
  for s in $PLATFORM_SERVICES; do
    printf '%s\n' "$services" | grep -qx "$s" || fail "service $s missing (have: $services)"
  done
  # every module is in the file; their dev provisioning is the one one-shot `provision`
  # (deploy/provision), never a per-module init
  printf '%s\n' "$services" | grep -qx provision || fail "the provision one-shot is missing"
  for d in "$REPO_DIR"/services/*/ "$REPO_DIR"/ui/*/; do
    s="$(basename "$d")"
    printf '%s\n' "$services" | grep -qx "$s" || fail "module $s is not a service of deploy/docker-compose.yml"
    [ -e "$d/init" ] && fail "$s still has an init/ folder (its provisioning belongs in deploy/provision/services.sh)"
    printf '%s\n' "$services" | grep -qx "$s-init" && fail "$s-init still in the stack"
  done
  return 0
}

